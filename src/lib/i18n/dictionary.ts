/**
 * The interface, in twelve languages.
 *
 * WHAT IS IN HERE AND WHAT IS NOT
 * -------------------------------
 * Only strings this project wrote: navigation, headings, buttons, labels and
 * its own explanatory prose. Nothing retrieved and nothing quoted.
 *
 * That boundary is the whole design. Every factual sentence in this product
 * is a quotation from a named source, and translating a quotation breaks it —
 * what reaches the reader would no longer be what the source said, while the
 * citation beside it would still claim it was. So the archive stays in its
 * source language, `notice.sourceLanguage` tells the reader that in their own
 * language, and the line between the two is a line in the code rather than a
 * matter of care.
 *
 * A missing key falls back to English rather than rendering the key itself:
 * an untranslated button is a small failure, `dest.stays` on screen is a
 * large one.
 */
export type MessageKey =
  | "nav.discover" | "nav.destinations" | "nav.compare" | "nav.experiences" | "nav.search"
  | "home.exploreDestinations" | "home.discoverByInterest" | "home.planJourney"
